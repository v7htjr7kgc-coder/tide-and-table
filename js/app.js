/* Tide & Table v2. Today's deal board. Data comes from data/deals.js (window.DEALS),
   generated by src/build.py from data/deals.json. Works over http(s) and from file://. */
(() => {
  "use strict";
  const DAYS = ["Mon","Tue","Wed","Thu","Fri","Sat","Sun"];
  const FULL = {Mon:"Monday",Tue:"Tuesday",Wed:"Wednesday",Thu:"Thursday",Fri:"Friday",Sat:"Saturday",Sun:"Sunday"};
  const $ = s => document.querySelector(s);
  const esc = s => String(s ?? "").replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
  const safeUrl = u => /^https?:\/\//i.test(u || "") ? u : "";
  const isFile = location.protocol === "file:";

  // clock (overridable for testing: ?now=16:45&today=Tue)
  const qs = new URLSearchParams(location.search);
  const realNow = new Date();
  let nowMin = realNow.getHours() * 60 + realNow.getMinutes();
  if (/^\d{1,2}:\d{2}$/.test(qs.get("now") || "")) { const [h, m] = qs.get("now").split(":").map(Number); nowMin = h * 60 + m; }
  const todayKey = DAYS.includes(qs.get("today")) ? qs.get("today") : DAYS[(realNow.getDay() + 6) % 7];

  const LS = { get: k => { try { return localStorage.getItem(k); } catch (e) { return null; } },
               set: (k, v) => { try { localStorage.setItem(k, v); } catch (e) {} } };

  const state = { data: null, origin: null, label: "", radius: 15, day: todayKey, food: "", dtype: "", unverified: true, mapOpen: false };
  let map = null, pinLayer = null, homeLayer = null; const pins = {};

  /* ---------- helpers ---------- */
  function haversine(a, b) {
    const R = 3958.8, rad = x => x * Math.PI / 180;
    const dLat = rad(b.lat - a.lat), dLng = rad(b.lng - a.lng);
    const h = Math.sin(dLat / 2) ** 2 + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(dLng / 2) ** 2;
    return 2 * R * Math.asin(Math.sqrt(h));
  }
  const fmtMin = m => { m = ((m % 1440) + 1440) % 1440; let h = Math.floor(m / 60), mm = m % 60; const ap = h >= 12 ? "PM" : "AM"; h = h % 12 || 12; return h + (mm ? ":" + String(mm).padStart(2, "0") : "") + " " + ap; };

  // Parse "3-6 PM", "4:30-6 PM", "11 AM-9 PM", "4 PM-close", "From 4 PM", "Until 4 PM", "3-6 PM & 9 PM-close".
  // Returns {allDay} | {evening} | {wins:[{s,e}]} | null. Parenthetical notes are ignored.
  const CLOSE = 23 * 60 + 59;
  function parseTime(raw) {
    const t0 = String(raw || "").toLowerCase();
    if (/^(all day|open-close|kitchen hours|open hours|from noon, all day)/.test(t0)) return { allDay: true };
    const t = t0.replace(/\([^)]*\)/g, " ");
    const wins = [];
    const re = /(\d{1,2})(?::(\d{2}))?\s*(am|pm)?\s*(?:-|–|—|to)\s*(?:(close|closing)|(\d{1,2})(?::(\d{2}))?\s*(am|pm)?)/g;
    let m;
    while ((m = re.exec(t))) {
      let sh = +m[1], sm = +(m[2] || 0), sap = m[3], eh, em, eap;
      if (m[4]) { eh = null; } else { eh = +m[5]; em = +(m[6] || 0); eap = m[7]; }
      if (eh !== null) {
        if (!eap) eap = sap || (eh <= 11 && eh >= 1 ? "pm" : "am");
        if (!sap) { sap = eap; const e24 = to24(eh, eap), s24 = to24(sh, sap); if (s24 > e24 && sh !== 12) sap = eap === "pm" ? "am" : "pm"; }
      } else if (!sap) sap = sh >= 7 && sh <= 11 && /am/.test(t) ? "am" : "pm";
      const s = to24(sh, sap) * 60 + sm;
      let e = eh === null ? CLOSE : to24(eh, eap) * 60 + em;
      if (e <= s) e += 1440;
      wins.push({ s, e });
    }
    if (!wins.length) {
      let f = t.match(/from\s+(\d{1,2})(?::(\d{2}))?\s*(am|pm)?/);
      if (f) { const s = to24(+f[1], f[3] || (+f[1] >= 7 && +f[1] <= 11 ? "am" : "pm")) * 60 + +(f[2] || 0); return { wins: [{ s, e: CLOSE }] }; }
      f = t.match(/until\s+(\d{1,2})(?::(\d{2}))?\s*(am|pm)?/);
      if (f) return { wins: [{ s: 11 * 60, e: to24(+f[1], f[3] || "pm") * 60 + +(f[2] || 0) }] };
      if (/dinner|evening|night/.test(t)) return { evening: true };
      return null;
    }
    return { wins };
  }
  function to24(h, ap) { h = h % 12; return ap === "pm" ? h + 12 : h; }

  // "Taco Tuesday: $3 Baja fish tacos, $3 soft tacos (...)" -> kicker "Taco Tuesday", headline "$3 Baja fish tacos", extra "..."
  function splitDeal(d) {
    let desc = String(d.description || "").trim(), kick = "", body = desc;
    const km = desc.match(/^([^:$]{2,38}):\s+(.+)$/);
    if (km) { kick = km[1]; body = km[2]; }
    if (d.headline) return { kick: kick || (d.deal_types || [])[0] || "", hl: d.headline, extra: body === d.headline ? "" : body };
    let depth = 0, cut = -1;
    for (let i = 0; i < body.length; i++) {
      const c = body[i];
      if (c === "(") depth++; else if (c === ")") depth = Math.max(0, depth - 1);
      else if (depth === 0 && (c === "," || c === ";") && i >= 10) { cut = i; break; }
      else if (depth === 0 && body.startsWith(" + ", i) && i >= 10) { cut = i; break; }
    }
    let hl = cut > 0 ? body.slice(0, cut) : body, extra = cut > 0 ? body.slice(cut + 1).replace(/^\s*\+?\s*/, "") : "";
    if (hl.length > 78) { const sp = hl.lastIndexOf(" ", 70); extra = hl.slice(sp + 1) + (extra ? ", " + extra : ""); hl = hl.slice(0, sp) + "…"; }
    if (!kick) kick = (d.deal_types || [])[0] || "";
    return { kick, hl, extra };
  }
  const hiPrice = s => esc(s).replace(/(\$\d+(?:\.\d{2})?(?:\s*-\s*\$?\d+(?:\.\d{2})?)?|\d+%\s*off|half[- ]off|\bfree\b|\bBOGO\b)/gi, "<em>$1</em>");

  /* ---------- data shaping ---------- */
  function visibleDeals(day) {
    const out = [];
    for (const r of state.data.restaurants) {
      if (state.food && r.food_type !== state.food) continue;
      if (r._dist > state.radius) continue;
      for (const d of r.deals) {
        if (!d.days.includes(day)) continue;
        if (state.dtype && !(d.deal_types || []).includes(state.dtype)) continue;
        if (!state.unverified && d.verify) continue;
        out.push({ r, d });
      }
    }
    return out;
  }
  const SECTIONS = [
    ["now", "On now"], ["morning", "Breakfast & brunch"], ["midday", "Lunch & afternoon"],
    ["hh", "Happy hour"], ["tonight", "Tonight"], ["allday", "All day"], ["check", "Check times"]];
  function classify(x, isToday) {
    const p = parseTime(x.d.time); x.p = p; x.state = "";
    if (!p) return "check";
    if (p.allDay) return "allday";
    if (p.evening) return "tonight";
    const w = p.wins;
    if (isToday) {
      const cur = w.find(v => nowMin >= v.s && nowMin < v.e);
      if (cur) { x.state = "now"; x.until = cur.e; return "now"; }
      const next = w.find(v => v.s > nowMin);
      if (next && next.s - nowMin <= 90) { x.state = "soon"; x.startsIn = next.s - nowMin; }
      if (!next && w.every(v => v.e <= nowMin)) x.state = "past";
    }
    const s = w[0].s;
    return s < 11 * 60 ? "morning" : s < 15 * 60 ? "midday" : s < 18 * 60 ? "hh" : "tonight";
  }

  /* ---------- render ---------- */
  function dealRow(x) {
    const { r, d } = x, sp = splitDeal(d), menu = safeUrl(r.menu_url), src = safeUrl(d.source_url), site = safeUrl(r.website);
    const days = d.days.length === 7 ? "daily" : "";
    let tag = "";
    if (x.state === "now") tag = `<span class="nowtag">On now · til ${esc(x.until >= CLOSE ? "close" : fmtMin(x.until))}</span>`;
    else if (x.state === "soon") tag = `<span class="soon">starts in ${x.startsIn} min</span>`;
    else if (x.state === "past") tag = `<span>ended</span>`;
    return `<article class="deal${x.state === "past" ? " past" : ""}" data-r="${esc(r.id)}">
      <div class="when"><span>${esc(d.time || "Hours vary")}</span>${tag}${days ? `<span>${days}</span>` : ""}</div>
      <div class="what">
        ${sp.kick ? `<p class="kick">${esc(sp.kick)}</p>` : ""}
        <h3 class="hl">${hiPrice(sp.hl)}</h3>
        ${sp.extra ? `<p class="extra">${hiPrice(sp.extra)}</p>` : ""}
        <p class="who"><b>${esc(r.name)}</b> <span class="d">${esc(r.city)} · ${r._dist.toFixed(1)} mi</span></p>
      </div>
      <div class="act">
        ${menu ? `<a class="menu" href="${esc(menu)}" target="_blank" rel="noopener" data-menu>Menu ↗</a>` : site ? `<a class="tiny" href="${esc(site)}" target="_blank" rel="noopener">website ↗</a><span class="nomenu">no menu online</span>` : `<span class="nomenu">no menu online</span>`}
        ${src ? `<a class="tiny" href="${esc(src)}" target="_blank" rel="noopener" title="${esc(d.source_note)}">source</a>` : ""}
        ${d.verify ? `<span class="confirm" title="${esc(d.source_note)}">call to confirm</span>` : ""}
      </div></article>`;
  }
  function render() {
    if (!state.data || !state.origin) return;
    for (const r of state.data.restaurants) r._dist = haversine(state.origin, r);
    // day tabs with counts
    $("#days").innerHTML = DAYS.map(k => {
      const n = visibleDeals(k).length;
      return `<button type="button" class="day${k === todayKey ? " today" : ""}" role="tab" aria-selected="${k === state.day}" data-day="${k}" title="${FULL[k]}${k === todayKey ? " (today)" : ""}"><b>${k}</b><small>${n}</small></button>`;
    }).join("");
    const isToday = state.day === todayKey;
    const items = visibleDeals(state.day);
    const groups = {}; SECTIONS.forEach(([k]) => groups[k] = []);
    for (const x of items) groups[classify(x, isToday)].push(x);
    const rank = x => (x.state === "past" ? 1 : 0);
    let html = `<div class="boardhead"><h1>${isToday ? "Today" : FULL[state.day]}</h1><p>${isToday ? FULL[state.day] + " · " + fmtMin(nowMin) + " · " : ""}${items.length} deals within ${state.radius} mi${state.food ? " · " + esc(state.food) : ""}</p></div>`;
    if (!items.length) html += `<p class="empty">Nothing matches. Try a wider radius, another day, or "All food".</p>`;
    for (const [k, title] of SECTIONS) {
      const g = groups[k]; if (!g.length) continue;
      g.sort((a, b) => rank(a) - rank(b) || a.r._dist - b.r._dist);
      const sub = k === "now" ? `${g.length} running right now` : k === "check" ? `${g.length} · hours not listed` : `${g.length}`;
      html += `<section class="sect ${k}"><h2>${title} <small>${sub}</small></h2><div class="rows">${g.map(dealRow).join("")}</div></section>`;
    }
    $("#board").innerHTML = html;
    if (map) drawMap(items);
    measureBar();
  }

  /* ---------- map (lazy) ---------- */
  function ensureMap() {
    if (map || !window.L) { if (!window.L) $("#map").innerHTML = '<p class="empty">Map needs an internet connection.</p>'; return; }
    map = L.map("map", { zoomSnap: 0.25, scrollWheelZoom: true }).setView([state.origin.lat, state.origin.lng], 11);
    L.tileLayer("https://tile.openstreetmap.org/{z}/{x}/{y}.png", { maxZoom: 19, className: "tiles",
      attribution: '© <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> contributors' }).addTo(map);
    homeLayer = L.layerGroup().addTo(map); pinLayer = L.layerGroup().addTo(map);
  }
  function drawMap(items) {
    pinLayer.clearLayers(); homeLayer.clearLayers(); for (const k in pins) delete pins[k];
    const o = state.origin;
    L.marker([o.lat, o.lng], { icon: L.divIcon({ className: "pin-home", iconSize: [14, 14] }), zIndexOffset: 1000, title: "You" }).addTo(homeLayer).bindPopup("<b>Search location</b><br>" + esc(state.label));
    L.circle([o.lat, o.lng], { radius: state.radius * 1609.34, color: "#13222B", weight: 1, dashArray: "4 4", fill: false, interactive: false }).addTo(homeLayer);
    const byR = new Map();
    for (const x of items) { if (!byR.has(x.r.id)) byR.set(x.r.id, { r: x.r, list: [] }); byR.get(x.r.id).list.push(x); }
    for (const { r, list } of byR.values()) {
      const on = list.some(x => x.state === "now");
      const menu = safeUrl(r.menu_url);
      const m = L.marker([r.lat, r.lng], { icon: L.divIcon({ className: "pin" + (on ? " now" : ""), iconSize: [12, 12] }), title: r.name });
      m.bindPopup(`<div class="pop"><b>${esc(r.name)}</b><br>${esc(splitDeal(list[0].d).hl)}${list.length > 1 ? ` <i>+${list.length - 1} more</i>` : ""}<br>${esc(list[0].d.time || "")} · ${r._dist.toFixed(1)} mi${menu ? `<br><a class="m" href="${esc(menu)}" target="_blank" rel="noopener">Menu ↗</a>` : ""}</div>`);
      m.on("click", () => focusRow(r.id));
      m.addTo(pinLayer); pins[r.id] = m;
    }
    map.fitBounds(L.latLng(o.lat, o.lng).toBounds(state.radius * 2 * 1609.34), { padding: [6, 6] });
  }
  function focusRow(id) {
    const el = document.querySelector(`.deal[data-r="${CSS.escape(id)}"]`); if (!el) return;
    document.querySelectorAll(".deal.hl").forEach(x => x.classList.remove("hl"));
    el.classList.add("hl"); el.scrollIntoView({ behavior: "smooth", block: "center" });
  }
  function setMap(open) {
    state.mapOpen = open;
    $("#mapBtn").setAttribute("aria-pressed", String(open));
    $("#mappane").hidden = !open; $("#layout").classList.toggle("map-open", open);
    if (open) { ensureMap(); if (map) { setTimeout(() => { map.invalidateSize(); render(); }, 30); } }
  }
  function measureBar() { document.documentElement.style.setProperty("--bar-h", $("#bar").offsetHeight + "px"); }

  /* ---------- location ---------- */
  async function geocode(q) {
    const key = "tt-geo:" + q.trim().toLowerCase(), c = LS.get(key);
    if (c) return JSON.parse(c);
    let hit = null;
    try {
      const r = await fetch("https://nominatim.openstreetmap.org/search?format=jsonv2&limit=1&countrycodes=us&q=" + encodeURIComponent(q), { headers: { Accept: "application/json" } });
      if (r.ok) { const j = await r.json(); if (j.length) hit = { lat: +j[0].lat, lng: +j[0].lon, label: j[0].display_name }; }
    } catch (e) {}
    if (!hit) {
      try {
        const r = await fetch("https://photon.komoot.io/api/?limit=1&lat=33.5&lon=-117.66&q=" + encodeURIComponent(q));
        if (r.ok) { const j = await r.json(), f = j.features && j.features[0];
          if (f) { const p = f.properties; hit = { lat: f.geometry.coordinates[1], lng: f.geometry.coordinates[0], label: [p.housenumber && p.street ? p.housenumber + " " + p.street : (p.name || p.street), p.city, p.state].filter(Boolean).join(", ") }; } }
      } catch (e) {}
    }
    if (hit) LS.set(key, JSON.stringify(hit));
    return hit;
  }
  const shortLabel = s => String(s).split(",").slice(0, 2).join(",").replace(/^(\d+),\s*/, "$1 ");
  function setOrigin(o, label, save) {
    state.origin = o; state.label = label;
    $("#locLabel").textContent = shortLabel(label);
    if (save) LS.set("tt-origin", JSON.stringify({ o, label }));
    render();
  }
  function locMsg(t, err) { const m = $("#locMsg"); m.textContent = t; m.classList.toggle("err", !!err); }
  function toggleLoc(open) {
    $("#locForm").hidden = !open; $("#locBtn").setAttribute("aria-expanded", String(open));
    if (open) { $("#addr").value = ""; $("#addr").placeholder = state.label ? shortLabel(state.label) : "Address, city or ZIP"; $("#addr").focus(); }
    measureBar();
  }

  /* ---------- wiring ---------- */
  function wire() {
    $("#locBtn").addEventListener("click", () => toggleLoc($("#locForm").hidden));
    $("#locForm").addEventListener("submit", async e => {
      e.preventDefault(); const q = $("#addr").value.trim(); if (!q) return;
      locMsg("Looking up “" + q + "”…"); $("#goBtn").disabled = true;
      const hit = await geocode(q); $("#goBtn").disabled = false;
      if (!hit) { locMsg("Couldn't find that. Add a city and state, or try a ZIP code.", true); return; }
      locMsg(""); toggleLoc(false); setOrigin({ lat: hit.lat, lng: hit.lng }, hit.label || q, true);
    });
    if (!("geolocation" in navigator)) $("#geoBtn").hidden = true;
    $("#geoBtn").addEventListener("click", () => {
      locMsg("Finding you…");
      navigator.geolocation.getCurrentPosition(p => {
        locMsg(""); toggleLoc(false); setOrigin({ lat: p.coords.latitude, lng: p.coords.longitude }, "Your location", false);
      }, () => locMsg(isFile ? "Your browser won't share location with a file opened from disk. Type an address instead." : "Couldn't get your location. Type an address instead.", true),
      { timeout: 10000, maximumAge: 300000 });
    });
    $("#radius").addEventListener("change", e => { state.radius = +e.target.value; render(); });
    $("#food").addEventListener("change", e => { state.food = e.target.value; render(); });
    $("#dtype").addEventListener("change", e => { state.dtype = e.target.value; render(); });
    $("#unverified").addEventListener("change", e => { state.unverified = e.target.checked; render(); });
    $("#moreBtn").addEventListener("click", () => { const open = $("#more").hidden; $("#more").hidden = !open; $("#moreBtn").setAttribute("aria-expanded", String(open)); measureBar(); });
    $("#mapBtn").addEventListener("click", () => setMap(!state.mapOpen));
    $("#mapClose").addEventListener("click", () => setMap(false));
    $("#days").addEventListener("click", e => { const b = e.target.closest(".day"); if (!b) return; state.day = b.dataset.day; render(); window.scrollTo({ top: 0 }); });
    window.addEventListener("resize", () => { measureBar(); if (map) map.invalidateSize(); });
  }
  function fillControls() {
    const foods = [...new Set(state.data.restaurants.map(r => r.food_type))].sort();
    $("#food").innerHTML = `<option value="">All food</option>` + foods.map(f => `<option>${esc(f)}</option>`).join("");
    const types = [...new Set(state.data.restaurants.flatMap(r => r.deals.flatMap(d => d.deal_types || [])))].sort();
    $("#dtype").innerHTML = `<option value="">Any kind of deal</option>` + types.map(t => `<option>${esc(t)}</option>`).join("");
    const u = state.data.meta && state.data.meta.updated;
    if (u) $("#updated").textContent = "· updated " + new Date(u + "T12:00:00").toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" });
  }

  async function init() {
    wire();
    state.data = window.DEALS || null;
    if (!state.data && !isFile) { try { state.data = await (await fetch("data/deals.json")).json(); } catch (e) {} }
    if (!state.data) { $("#board").innerHTML = '<p class="empty">Deal data didn\'t load (data/deals.js is missing). Run src/build.py.</p>'; return; }
    fillControls();
    const saved = LS.get("tt-origin"), h = state.data.meta && state.data.meta.home;
    if (saved && !qs.has("reset")) { const s = JSON.parse(saved); setOrigin(s.o, s.label, false); }
    else if (h) setOrigin({ lat: h.lat, lng: h.lng }, h.label, false);
    else { toggleLoc(true); }
    if (qs.get("map") === "1") setMap(true);
  }
  window.__tt = { parseTime, splitDeal }; // exposed for the test script
  init();
})();
